// Generates packages/contracts/src/generated/{schemas.json,openapi.json,types.ts} from docs/contracts.
// docs/contracts is the single normative source; `--check` fails when the generated copy has drifted.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Schema = Record<string, unknown>;

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const sourceDir = join(root, 'docs', 'contracts');
const outDir = join(root, 'packages', 'contracts', 'src', 'generated');
const check = process.argv.includes('--check');

const schemasText = readFileSync(join(sourceDir, 'schemas.json'), 'utf8');
const openapiText = readFileSync(join(sourceDir, 'openapi.json'), 'utf8');
const schemas = JSON.parse(schemasText) as { $defs: Record<string, Schema> };

// Avoid shadowing ECMAScript globals in consumers.
const renamed: Record<string, string> = { Date: 'CalendarDate', Error: 'ApiError' };

function typeName(def: string): string {
  return renamed[def] ?? def.replace(/[^A-Za-z0-9]+/g, '_');
}

function literal(value: unknown): string {
  return JSON.stringify(value);
}

function render(schema: Schema, indent: string): string {
  if (typeof schema.$ref === 'string') {
    const name = schema.$ref.replace('#/$defs/', '');
    return typeName(name);
  }
  if ('const' in schema) return literal(schema.const);
  if (Array.isArray(schema.enum)) return (schema.enum as unknown[]).map(literal).join(' | ');
  if (Array.isArray(schema.oneOf)) {
    return (schema.oneOf as Schema[]).map((s) => `(${render(s, indent)})`).join(' | ');
  }
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return `Array<${render((schema.items ?? {}) as Schema, indent)}>`;
    case 'object': {
      const props = (schema.properties ?? {}) as Record<string, Schema>;
      const required = new Set((schema.required ?? []) as string[]);
      const inner = indent + '  ';
      const lines = Object.entries(props).map(([key, value]) => {
        const safeKey = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : literal(key);
        return `${inner}readonly ${safeKey}${required.has(key) ? '' : '?'}: ${render(value, inner)};`;
      });
      if (lines.length === 0) return 'Record<string, never>';
      return `{\n${lines.join('\n')}\n${indent}}`;
    }
    default:
      return 'unknown';
  }
}

const header =
  '// GENERATED by tools/contracts/generate.ts from docs/contracts/schemas.json. Do not edit.\n' +
  '/* eslint-disable */\n';
const body = Object.entries(schemas.$defs)
  .map(([name, schema]) => `export type ${typeName(name)} = ${render(schema, '')};`)
  .join('\n\n');
const defNames = `export const schemaDefinitionNames = ${JSON.stringify(Object.keys(schemas.$defs), null, 2)} as const;\n`;
const typesText = `${header}\n${body}\n\n${defNames}`;

const outputs: Array<[string, string]> = [
  ['schemas.json', schemasText],
  ['openapi.json', openapiText],
  ['types.ts', typesText],
];

if (check) {
  const drift = outputs.filter(([file, text]) => {
    try {
      return readFileSync(join(outDir, file), 'utf8') !== text;
    } catch {
      return true;
    }
  });
  if (drift.length > 0) {
    console.error(`contracts drift: ${drift.map(([f]) => f).join(', ')}; run npm run contracts:generate`);
    process.exit(1);
  }
  console.log('contracts: generated copy matches docs/contracts');
} else {
  mkdirSync(outDir, { recursive: true });
  for (const [file, text] of outputs) writeFileSync(join(outDir, file), text);
  console.log(`contracts: wrote ${outputs.length} files to ${outDir}`);
}
